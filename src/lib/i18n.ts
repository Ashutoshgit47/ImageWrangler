export type TranslationKey = keyof typeof translations['en'];

const STORAGE_KEY = 'imagewrangler_locale';

export function getInitialLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as Locale;
    if (saved && translations[saved]) {
      return saved;
    }
    const navLang = navigator.language?.slice(0, 2).toLowerCase() as Locale;
    if (navLang && translations[navLang]) {
      return navLang;
    }
  } catch {
    // Ignore localStorage errors
  }
  return 'en';
}

export function translate(
  key: TranslationKey,
  locale: Locale = 'en',
  params?: Record<string, string | number>
): string {
  const dict = translations[locale] || translations['en'];
  let text = dict[key] || translations['en'][key] || key;

  if (params) {
    Object.entries(params).forEach(([paramKey, value]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(value));
    });
  }

  return text;
}

/**
 * Custom React Hook for i18n
 */
export function useTranslation() {
  const [currentLocale, setCurrentLocale] = useState<Locale>('en');

  useEffect(() => {
    setCurrentLocale(getInitialLocale());
  }, []);

  const changeLocale = useCallback((newLocale: Locale) => {
    if (translations[newLocale]) {
      setCurrentLocale(newLocale);
      try {
        localStorage.setItem(STORAGE_KEY, newLocale);
      } catch {
        // Ignore storage errors
      }
    }
  }, []);

  const t = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>) => {
      return translate(key, currentLocale, params);
    },
    [currentLocale]
  );

  return {
    currentLocale,
    changeLocale,
    t,
    locales: SUPPORTED_LOCALES,
  };
}
